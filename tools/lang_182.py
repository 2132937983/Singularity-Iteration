def main():
    index = {'en_us': 0, 'zh_cn': 1, 'ja_jp': 2}
    for lang, table in ADD.items():
        path = os.path.join(LANG, lang + '.json')
        with open(path, encoding='utf-8') as f:
            data = json.load(f, object_pairs_hook=OrderedDict)
        plants = 0
        for pid, names in PLANTS.items():
            key = P + pid
            if lang in PLANT_FILL_ONLY and key in data:
                continue
            data[key] = names[index[lang]]
            plants += 1
        for k, v in table.items():
            data[k] = v
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=2, ensure_ascii=False)
            f.write('\n')
        print(lang, 'keys set:', len(table), 'plant names set:', plants)


if __name__ == '__main__':
    main()
